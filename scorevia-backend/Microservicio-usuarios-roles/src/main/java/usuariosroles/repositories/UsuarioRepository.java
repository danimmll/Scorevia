package usuariosroles.repositories;

import java.util.List;
import java.util.Optional;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.CrudRepository;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;
import usuariosroles.entities.Usuario;

/**
 * Spring Data JPA repository for the {@link Usuario} entity.
 *
 * <p>Provides basic CRUD operations inherited from {@link CrudRepository}
 * and custom query methods to retrieve users based on specific criteria.</p>
 *
 * <p>The implementation of this interface is automatically generated by Spring Data
 * based on the declared method signatures.</p>
 *
 * @author Daniel
 * @version 1.0
 */
@Repository
public interface UsuarioRepository extends CrudRepository<Usuario, Integer> {

    /**
     * Finds all users by their active status.
     *
     * @param activo Active status of the user ({@code true} = active, {@code false} = inactive).
     * @param pageable Pagination information.
     * @return Page of users matching the criteria.
     */
    Page<Usuario> findAllByActivo(Boolean activo, Pageable pageable);

    /**
     * Checks if a user exists with a specific email address.
     *
     * @param correoUsuario Email address of the user.
     * @return {@code true} if it exists, {@code false} otherwise.
     */
    boolean existsByCorreoUsuario(String correoUsuario);

    /**
     * Checks if a user exists with a specific nickname.
     *
     * @param nickname Nickname of the user.
     * @return {@code true} if it exists, {@code false} otherwise.
     */
    boolean existsByNickname(String nickname);

    /**
     * Finds a user by their identifier and active status.
     *
     * @param idUsuario User identifier.
     * @param activo Active status of the user.
     * @return {@link Optional} containing the user if found, or empty if not found.
     */
    Optional<Usuario> findByIdUsuarioAndActivo(Integer idUsuario, boolean activo);

    /**
     * Checks if a user exists with a specific id and active status. Usado internamente para
     * revalidar que un usuario con una sesión larga abierta sigue activo.
     *
     * @param idUsuario User identifier.
     * @param activo Active status of the user.
     * @return {@code true} if it exists and matches, {@code false} otherwise.
     */
    boolean existsByIdUsuarioAndActivo(Integer idUsuario, boolean activo);

    /**
     * Checks if a user exists with a specific email address and active status.
     *
     * @param correoUsuario Email address of the user.
     * @param activo Active status of the user.
     * @return {@code true} if it exists, {@code false} otherwise.
     */
    boolean existsByCorreoUsuarioAndActivo(String correoUsuario, Boolean activo);

    /**
     * Finds a user by their email address.
     *
     * @param correoUsuario Email address of the user.
     * @return {@link Optional} containing the user if found, or empty if not found.
     */
    Optional<Usuario> findByCorreoUsuario(String correoUsuario);

    /**
     * Retrieves all users with pagination.
     *
     * @param pageable Pagination information.
     * @return Page of all users.
     */
    Page<Usuario> findAll(Pageable pageable);

    /**
     * Paginación por keyset (no por OFFSET) ordenada por id: usada para el export a Excel
     * de toda la tabla en lotes acotados sin materializarla entera en memoria. A diferencia
     * de {@code PageRequest.of(pagina, tamaño)} con OFFSET, este patrón no degrada con
     * páginas profundas -- cada lote solo cuesta un índice sobre la PK.
     *
     * @param idUsuario Id a partir del cual (exclusive) buscar el siguiente lote.
     * @param pageable  Solo se usa su tamaño de página (el "page number" se ignora, siempre
     *                  se pide desde 0 -- el avance real lo da el idUsuario del último visto).
     * @return Hasta {@code pageable.getPageSize()} usuarios con id mayor que el dado.
     */
    List<Usuario> findByIdUsuarioGreaterThanOrderByIdUsuarioAsc(Integer idUsuario, Pageable pageable);
}
