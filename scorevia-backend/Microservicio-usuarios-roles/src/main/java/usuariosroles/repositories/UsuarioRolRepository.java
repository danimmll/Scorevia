package usuariosroles.repositories;

import java.util.List;
import java.util.Optional;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.stereotype.Repository;
import usuariosroles.entities.UsuarioRol;
import usuariosroles.models.UsuarioRolId;

/**
 * Spring Data JPA repository for the {@link UsuarioRol} entity.
 *
 * <p>Provides basic CRUD operations inherited from {@link JpaRepository}
 * and custom query methods to retrieve user-role assignments based on specific criteria.</p>
 *
 * <p>The implementation of this interface is automatically generated by Spring Data
 * based on the declared method signatures.</p>
 *
 * @author Daniel
 * @version 1.0
 */
@Repository
public interface UsuarioRolRepository extends JpaRepository<UsuarioRol, UsuarioRolId> {

    /**
     * Finds all role assignments for a specific user.
     *
     * @param id Identifier of the user.
     * @return List of {@link UsuarioRol} assignments for the given user.
     */
    List<UsuarioRol> findByUsuarioIdUsuario(Integer id);

    /**
     * Finds all user assignments for a specific role.
     *
     * @param id Identifier of the role.
     * @return List of {@link UsuarioRol} assignments for the given role.
     */
    List<UsuarioRol> findByRolIdRol(Integer id);

    /**
     * Finds a specific user-role assignment by user ID and role ID.
     *
     * @param i User identifier.
     * @param j Role identifier.
     * @return {@link Optional} containing the assignment if found, or empty if not found.
     */
    Optional<UsuarioRol> findByUsuarioIdUsuarioAndRolIdRol(int i, int j);

    /**
     * Paginated listing of every user-role assignment (admin-only endpoint). Without
     * pagination this table grows unbounded with users × roles.
     */
    Page<UsuarioRol> findAll(Pageable pageable);
}
